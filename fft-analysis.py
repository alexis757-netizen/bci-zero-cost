import numpy as np
import matplotlib.pyplot as plt

# 1. 设定采样率和时间轴
fs = 250  # 采样率 250 Hz（这是脑电采集的标准频率）
t = np.arange(0, 2, 1/fs)  # 持续 2 秒的时间轴

# 2. 模拟大脑产生的两段脑电波
# 10Hz 的 Alpha 波（幅度较小）
alpha_wave = 0.5 * np.sin(2 * np.pi * 10 * t)
# 20Hz 的 Beta 波（幅度较大）
beta_wave = 1.0 * np.sin(2 * np.pi * 20 * t)
# 加入一点随机噪声
noise = 0.3 * np.random.randn(len(t))

# 混合信号（这就相当于你头皮上采集到的真实原始信号）
eeg_signal = alpha_wave + beta_wave + noise

# ---- 画图第一步：时域波形（随时间的变化） ----
plt.figure(figsize=(12, 8))
plt.subplot(2, 1, 1)
plt.plot(t, eeg_signal)
plt.title("Time Domain: Mixed EEG Signal (Looks messy, right?)")
plt.xlabel("Time (s)")
plt.ylabel("Amplitude")

# ---- 核心步骤：FFT 快速傅里叶变换（把时间变成频率） ----
# 使用 numpy 自带的 fft 函数
fft_result = np.fft.fft(eeg_signal)
# 获取频率轴（从 0 到 fs/2）
freqs = np.fft.fftfreq(len(eeg_signal), 1/fs)
# 只看正半部分的频率，并计算真实的幅度
positive_freqs = freqs[:len(freqs)//2]
amplitudes = np.abs(fft_result)[:len(fft_result)//2] * (2 / len(eeg_signal))

# ---- 画图第二步：频域频谱图（随频率的分布） ----
plt.subplot(2, 1, 2)
plt.plot(positive_freqs, amplitudes)
plt.title("Frequency Domain (FFT): We can clearly see 10Hz and 20Hz peaks!")
plt.xlabel("Frequency (Hz)")
plt.ylabel("Amplitude")
plt.xlim(0, 40) # 我们只关心 0~40Hz 的脑电波段
plt.grid(True)

plt.tight_layout()
plt.show()