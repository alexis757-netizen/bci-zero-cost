import mne
import numpy as np
import matplotlib.pyplot as plt
from mne.decoding import CSP
from sklearn.svm import SVC
from sklearn.pipeline import Pipeline
from sklearn.model_selection import cross_val_score, KFold
import warnings
warnings.filterwarnings("ignore")

# 2. 加载数据并滤波
print("Loading EEG data...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[4])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
raw.filter(l_freq=8.0, h_freq=30.0, verbose=False)

# 3. 提取事件
events, event_id = mne.events_from_annotations(raw, verbose=False)
event_id_binary = {'T1': event_id['T1'], 'T2': event_id['T2']}

# 4. 【核心升级】滑动窗口数据增强
print("Applying Sliding Window Augmentation...")
fs = raw.info['sfreq']
data_all = raw.get_data() * 1e6  # 单位转为微伏
X_augmented = []
y_augmented = []

# 设置参数
window_size = int(1.0 * fs)  # 每个样本 1 秒长（大约 160 个点）
step_size = int(0.2 * fs)    # 每次滑动 0.2 秒（大约 32 个点）

for event in events:
    # 过滤掉不要的事件（只处理 T1 和 T2）
    if event[2] not in [event_id_binary['T1'], event_id_binary['T2']]:
        continue

    label = event[2]
    # 事件发生的时间点（sample index）
    start_idx = event[0] + int(0.5 * fs) # 从 0.5 秒后开始截取，避开初期反应延迟
    end_idx = event[0] + int(3.5 * fs)   # 到 3.5 秒结束

    # 开始在这个 3 秒区间内滑动
    for i in range(start_idx, end_idx - window_size, step_size):
        window_data = data_all[:, i : i + window_size]
        X_augmented.append(window_data)
        y_augmented.append(label)

X = np.array(X_augmented)
y = np.array(y_augmented)
print(f"Original data shape (approx): (15, 64, 640)")
print(f"Augmented data shape: {X.shape}") # 样本量瞬间暴涨！

# 5. 构建流水线
csp = CSP(n_components=4, reg=None, log=True, norm_trace=False)
svm = SVC(kernel='linear')
clf = Pipeline([('CSP', csp), ('SVM', svm)])

# 6. 重新进行交叉验证
print("\nStarting 5-Fold Cross-Validation on Augmented Data...")
kf = KFold(n_splits=5, shuffle=True, random_state=42)
scores = cross_val_score(clf, X, y, cv=kf)

print(f"Scores for each fold: {np.round(scores, 4)}")
print(f"Mean Accuracy: {scores.mean() * 100:.2f}%")
print(f"Standard Deviation: {scores.std() * 100:.2f}%")

# 7. 画图
plt.figure(figsize=(8, 5))
plt.bar(range(1, 6), scores * 100, color='lightgreen', edgecolor='black')
plt.axhline(y=scores.mean() * 100, color='red', linestyle='--', label='Mean Accuracy')
plt.title("5-Fold Cross-Validation (Augmented Data)")
plt.xlabel("Fold Number")
plt.ylabel("Accuracy (%)")
plt.ylim(0, 100)
plt.legend()
plt.show()