import mne
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import welch

# 1. 加载闭眼数据 (runs=[2])
print("正在加载闭眼状态的脑电数据...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[2])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)

# 滤波
raw.filter(l_freq=1.0, h_freq=40.0, verbose=False)
raw.notch_filter(freqs=50.0, verbose=False)

# 2. 专门找枕区通道 (O1 或 Oz)
target_ch = 'O1'
if 'O1..' in raw.ch_names:
    target_ch = 'O1..'
elif 'Oz..' in raw.ch_names:
    target_ch = 'Oz..'
else:
    # 如果都没找到，就模糊搜索
    for ch in raw.ch_names:
        if 'O1' in ch or 'Oz' in ch:
            target_ch = ch
            break

print(f"最终选中的后脑勺通道是: {target_ch}")
ch_idx = raw.ch_names.index(target_ch)

# 提取整个 10 秒数据
data_array, times = raw[ch_idx:ch_idx+1, :int(10 * raw.info['sfreq'])]
signal = data_array[0] * 1e6
signal = signal - np.mean(signal)

# 3. 使用 Welch 方法计算 PSD（功率谱密度）
fs = raw.info['sfreq']
# nperseg 是每段的长度，Welch 会将信号切段处理
freqs, psd = welch(signal, fs, nperseg=int(fs*2))

# 4. 画图（使用对数坐标 dB）
plt.figure(figsize=(12, 6))
# 只画 0-40Hz 的部分
valid_idx = freqs <= 40
plt.plot(freqs[valid_idx], 10 * np.log10(psd[valid_idx]), color='blue', linewidth=2)

plt.title(f"Frequency Domain (Welch PSD) - Channel {target_ch} (Eyes Closed)")
plt.xlabel("Frequency (Hz)")
plt.ylabel("Power Spectral Density (dB)")
plt.xlim(0, 40)
plt.grid(True)

# 标出 Alpha 和 Beta 区域
plt.axvspan(8, 13, color='yellow', alpha=0.3, label='Alpha (8-13Hz)')
plt.axvspan(13, 30, color='red', alpha=0.1, label='Beta (13-30Hz)')
plt.legend()

plt.tight_layout()
plt.show()