import mne
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import welch
from scipy.integrate import simpson as simps

# 1. 加载数据（runs=[7] 代表想象左手/右手运动的实验）
print("正在加载运动想象数据...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[7])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
raw.filter(l_freq=1.0, h_freq=40.0, verbose=False)
raw.notch_filter(freqs=50.0, verbose=False)

# 2. 找到 C3 (左脑，控右手) 和 C4 (右脑，控左手) 通道
ch_c3 = [ch for ch in raw.ch_names if 'C3' in ch][0]
ch_c4 = [ch for ch in raw.ch_names if 'C4' in ch][0]
print(f"提取通道: {ch_c3} 和 {ch_c4}")

# 3. 定义一个“特征提取函数”：计算特定频段的能量
def extract_band_power(signal, fs, fmin, fmax):
    # 使用 Welch 法计算功率谱密度
    freqs, psd = welch(signal, fs, nperseg=int(fs*1))
    # 找到我们要的频率范围（比如 8-13Hz）
    idx_band = np.logical_and(freqs >= fmin, freqs <= fmax)
    # 使用辛普森法则计算这段频谱下的“面积”（即总能量）
    band_power = simps(psd[idx_band], freqs[idx_band])
    return band_power

# 4. 用滑动窗口提取整个时间段的能量变化
fs = raw.info['sfreq']
data_c3 = raw.get_data(picks=[ch_c3])[0] * 1e6
data_c4 = raw.get_data(picks=[ch_c4])[0] * 1e6

window_size = int(fs * 1) # 1秒的窗口
step_size = int(fs * 0.1) # 每次滑动0.1秒
c3_powers = []
c4_powers = []
times = []

for start in range(0, len(data_c3) - window_size, step_size):
    end = start + window_size
    # 提取 8-13Hz 的能量
    p_c3 = extract_band_power(data_c3[start:end], fs, 8, 13)
    p_c4 = extract_band_power(data_c4[start:end], fs, 8, 13)

    c3_powers.append(p_c3)
    c4_powers.append(p_c4)
    times.append(start / fs)

# 5. 画图展示
plt.figure(figsize=(12, 5))
plt.plot(times, c3_powers, label=f'{ch_c3} (Left Brain)', color='blue', alpha=0.8)
plt.plot(times, c4_powers, label=f'{ch_c4} (Right Brain)', color='red', alpha=0.8)

plt.title("Feature Extraction: 8-13Hz Energy over Time (Motor Imagery)")
plt.xlabel("Time (s)")
plt.ylabel("Band Power (Energy)")
plt.legend()
plt.grid(True)
plt.xlim(0, 60) # 只看前60秒
plt.show()