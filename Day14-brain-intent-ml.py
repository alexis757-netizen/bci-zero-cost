import mne
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import welch
from scipy.integrate import simpson as simps
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, ConfusionMatrixDisplay
import warnings
warnings.filterwarnings("ignore")

# ================= 2. 数据加载 =================
print("Loading EEG data...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[4])[0]
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
raw.filter(l_freq=1.0, h_freq=40.0, verbose=False)

events, event_id = mne.events_from_annotations(raw, verbose=False)
epochs = mne.Epochs(raw, events, event_id, tmin=1.0, tmax=5.0, baseline=None, preload=True, verbose=False)

# ================= 3. 特征提取 =================
ch_c3 = [ch for ch in raw.ch_names if 'C3' in ch][0]
ch_c4 = [ch for ch in raw.ch_names if 'C4' in ch][0]
fs = raw.info['sfreq']

def extract_band_power(signal, fs, fmin, fmax):
    """Extract band power from a specific frequency range"""
    freqs, psd = welch(signal, fs, nperseg=int(fs*1))
    idx_band = np.logical_and(freqs >= fmin, freqs <= fmax)
    return simps(psd[idx_band], freqs[idx_band])

X, y = [], []
for i in range(len(epochs)):
    data = epochs.get_data()[i] * 1e6
    c3_data = data[raw.ch_names.index(ch_c3)]
    c4_data = data[raw.ch_names.index(ch_c4)]

    p_c3 = extract_band_power(c3_data, fs, 8, 13)
    p_c4 = extract_band_power(c4_data, fs, 8, 13)

    X.append([p_c3, p_c4])
    y.append(epochs.events[i, 2])

# ================= 4. 模型训练 =================
X_train, X_test, y_train, y_test = train_test_split(np.array(X), np.array(y), test_size=0.3, random_state=42)

print("Training AI model...")
clf = RandomForestClassifier(n_estimators=100, random_state=42)
clf.fit(X_train, y_train)

# ================= 5. 评估与可视化 =================
y_pred = clf.predict(X_test)
accuracy = accuracy_score(y_test, y_pred)
print(f"\nModel Accuracy: {accuracy * 100:.2f}%")

plt.figure(figsize=(6, 6))
ConfusionMatrixDisplay.from_estimator(
    clf, X_test, y_test,
    display_labels=['Rest (T0)', 'Left Hand (T1)', 'Right Hand (T2)'],
    cmap=plt.cm.Blues
)
plt.title("Confusion Matrix (Brain Intent Prediction)")
plt.show()