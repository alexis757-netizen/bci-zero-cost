import mne
import numpy as np
import matplotlib.pyplot as plt

# 1. 下载真实脑电数据（注意这里改成了 subjects=[1]）
print("正在下载真实脑电数据，请稍候...")
data_path = mne.datasets.eegbci.load_data(subjects=[1], runs=[1])[0]

# 2. 读取数据
raw = mne.io.read_raw_edf(data_path, preload=True, verbose=False)
print("数据加载成功！")

# 3. 提取前 10 秒的第一个通道
data, times = raw[:1, :int(10 * raw.info['sfreq'])]
channel_data = data[0] * 1e6  # 转换为微伏

# 4. 施加带通滤波（只保留 1Hz 到 40Hz）
print("正在进行 1-40Hz 带通滤波...")
filtered_raw = raw.copy().filter(l_freq=1.0, h_freq=40.0, verbose=False)
filtered_data, _ = filtered_raw[:1, :int(10 * raw.info['sfreq'])]
filtered_channel_data = filtered_data[0] * 1e6

# 5. 画图对比
plt.figure(figsize=(12, 6))

# 上图：原始脏数据
plt.subplot(2, 1, 1)
plt.plot(times, channel_data, color='gray')
plt.title("Before Filtering (Raw Data)")
plt.ylabel("Amplitude (µV)")
plt.grid(True)

# 下图：滤波后的干净数据
plt.subplot(2, 1, 2)
plt.plot(times, filtered_channel_data, color='green')
plt.title("After 1-40Hz Bandpass Filtering (Cleaner EEG)")
plt.xlabel("Time (s)")
plt.ylabel("Amplitude (µV)")
plt.grid(True)

plt.tight_layout()
plt.show()
# 我们只看第 2 秒到第 3 秒这 1 秒钟的数据
start_idx = int(2 * raw.info['sfreq'])
end_idx = int(3 * raw.info['sfreq'])

plt.figure(figsize=(12, 6))

# 图 1：放大看原始数据
plt.subplot(2, 1, 1)
plt.plot(times[start_idx:end_idx], channel_data[start_idx:end_idx], color='gray')
plt.title("Before Filtering (Zoomed in 1s) - Notice the fuzzy high-frequency noise")
plt.ylabel("Amplitude (µV)")
plt.grid(True)

# 图 2：放大看滤波后数据
plt.subplot(2, 1, 2)
plt.plot(times[start_idx:end_idx], filtered_channel_data[start_idx:end_idx], color='green')
plt.title("After Filtering (Zoomed in 1s) - Much smoother!")
plt.xlabel("Time (s)")
plt.ylabel("Amplitude (µV)")
plt.grid(True)

plt.tight_layout()
plt.show()
plt.figure(figsize=(12, 4))
# 算出差值：原始 - 滤波 = 被滤掉的部分
noise_removed = channel_data - filtered_channel_data
plt.plot(times, noise_removed, color='red')
plt.title("What the Filter Removed (High & Low Frequency Noise)")
plt.xlabel("Time (s)")
plt.ylabel("Amplitude (µV)")
plt.grid(True)
plt.show()